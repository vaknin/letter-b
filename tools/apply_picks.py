# Puts Aviv's picks from voices-pick.html into the site, in one command:
#   uv run tools/apply_picks.py "book 3 · bag 1 · what 2 · he1 2"
# - a picked word or sentence: that take becomes its clip in CLIPS (index.html);
# - every other line the site says (PHRASES(LESSON)) is in the style of the take number he picked most
#   (tools/takes.py STYLES): that take where the picker has one, else recorded again in the same voice
#   (DEVICE=cuda on a GPU; about 45 s a line on this server's CPU), so the whole site is one voice;
# - a picked Hebrew line goes into HE_CLIPS: an instruction plays when its stage opens, a word meaning
#   after the English word in "Meet the words". Hebrew he didn't pick stays silent.
# Python for the same reason as takes.py: OmniVoice is a PyTorch model only.
import base64, collections, json, re, sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import takes  # noqa: E402

FILE = takes.ROOT / "index.html"


def parse(line):
    picks = {}
    for part in re.split(r"[·,;\n]+", line):
        m = re.fullmatch(r"\s*(\S+)\s+(\d)\s*", part)
        if part.strip() and not m:
            sys.exit(f"can't read {part.strip()!r}: write it as 'book 3'")
        if m:
            picks[m[1]] = int(m[2])
    return picks


def uri(path):
    return "data:audio/mpeg;base64," + base64.b64encode(path.read_bytes()).decode()


def block(src, begin, end, body):
    a, b = src.index(begin), src.index(end)
    return src[:a] + body + src[b:]


def main():
    if len(sys.argv) != 2:
        sys.exit('usage: uv run tools/apply_picks.py "book 3 · bag 1 · he1 2"')
    picks = parse(sys.argv[1])
    man = json.loads((takes.TAKES / "takes.json").read_text())
    rows = {key: (text, lang, n) for key, text, lang, n in takes.items()}
    for key, k in picks.items():
        if key not in rows or not 1 <= k <= rows[key][2]:
            sys.exit(f"no take {key} {k} (keys: {', '.join(rows)})")
    phrases = takes.lesson()["phrases"]
    en = {rows[k][0]: man[f"{k} {n}"] for k, n in picks.items() if rows[k][1] == "en"}
    he = {rows[k][0]: man[f"{k} {n}"] for k, n in picks.items() if rows[k][1] == "he"}
    counts = collections.Counter(n for k, n in picks.items() if rows[k][1] == "en")
    style = min(counts, key=lambda n: (-counts[n], n)) if counts else 1

    clips, tmp = {}, takes.TAKES / "_apply.mp3"
    texts = {text: key for key, (text, lang, n) in rows.items() if lang == "en"}
    for p in phrases:
        if p in en:
            clips[p] = uri(takes.TAKES / en[p]["file"])
            continue
        if p in texts and f"{texts[p]} {style}" in man:  # a line on the picker he didn't pick: its take in that style
            clips[p] = uri(takes.TAKES / man[f"{texts[p]} {style}"]["file"])
            continue
        dt = takes.say(p, "en", style, tmp)
        clips[p] = uri(tmp)
        print(f"recorded {p!r} in style {style} ({takes.STYLES[style]['name']}): {dt:.1f} s", flush=True)
    tmp.unlink(missing_ok=True)
    he_clips = {t: uri(takes.TAKES / v["file"]) for t, v in he.items()}

    src = FILE.read_text()
    voice = f"OmniVoice, {takes.VOICE}, cloned from tools/takes/voice-ref.wav"
    body = ",\n".join(f"  {json.dumps(p)}: \"{clips[p]}\"" for p in phrases)
    src = block(src, "/* CLIPS:BEGIN", "/* CLIPS:END */",
                f"/* CLIPS:BEGIN – generated by tools/apply_picks.py ({voice}; picks: {sys.argv[1]}; the rest in style {style}), do not edit by hand */\nconst CLIPS = {{\n{body}\n}};\n")
    hbody = ",\n".join(f"  {json.dumps(t, ensure_ascii=False)}: \"{u}\"" for t, u in he_clips.items())
    src = block(src, "/* HE_CLIPS:BEGIN", "/* HE_CLIPS:END */",
                f"/* HE_CLIPS:BEGIN – generated by tools/apply_picks.py ({voice}), do not edit by hand */\nconst HE_CLIPS = {{\n{hbody}\n}};\n")
    FILE.write_text(src)
    print(f"{len(en)} English picks, {len(phrases) - len(en)} lines recorded again, {len(he_clips)} Hebrew lines: index.html written")


if __name__ == "__main__":
    main()
