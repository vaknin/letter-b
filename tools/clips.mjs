// Records every line the site can say (PHRASES(LESSON) in index.html) with a child voice
// and writes them into the CLIPS map in index.html as base64 mp3 data URIs.
// Run after changing LESSON:  node tools/clips.mjs   (needs uvx and ffmpeg; edge-tts is free, no key)
// Another voice in one command:  VOICE=en-US-GuyNeural PITCH=+10Hz RATE=-5% node tools/clips.mjs
// (list voices: uvx edge-tts --list-voices)
// Silence at both ends is cut so a clip starts the moment it's asked for.
// ---- the voice: change these three, or override them on the command line as above ----
const VOICE = process.env.VOICE || 'en-US-AnaNeural';
const PITCH = process.env.PITCH || '-15Hz';
const RATE = process.env.RATE || '-15%';
// ----

import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'fs';
import { execFile } from 'child_process';
import { tmpdir } from 'os';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const FILE = path.join(here, '..', 'index.html');
const BEGIN = '/* CLIPS:BEGIN', END = '/* CLIPS:END */';

const html = readFileSync(FILE, 'utf8');
const code = html.slice(html.indexOf('const LESSON = {'), html.indexOf(BEGIN));
const phrases = new Function(code + '\nreturn PHRASES(LESSON);')();

const dir = mkdtempSync(path.join(process.env.CLAUDE_JOB_DIR ? path.join(process.env.CLAUDE_JOB_DIR, 'tmp') : tmpdir(), 'clips-'));
const run = (cmd, args) => new Promise((res, rej) => execFile(cmd, args, { timeout: 60000 }, e => e ? rej(e) : res()));
const trim = 'silenceremove=start_periods=1:start_threshold=-50dB';
const tts = async (text, out) => {
  await run('uvx', ['edge-tts', '--voice', VOICE, `--rate=${RATE}`, `--pitch=${PITCH}`, '--text', text, '--write-media', out + '.raw.mp3']);
  await run('ffmpeg', ['-v', 'error', '-y', '-i', out + '.raw.mp3', '-af', `${trim},areverse,${trim},areverse,adelay=40`, '-ac', '1', '-ar', '24000', '-b:a', '40k', out]);
};

const clips = {};
let next = 0;
async function worker() {
  while (next < phrases.length) {
    const k = next++, text = phrases[k], out = path.join(dir, k + '.mp3');
    for (let t = 1; ; t++) { try { await tts(text, out); break; } catch (e) { if (t === 3) throw e; } }
    clips[text] = 'data:audio/mpeg;base64,' + readFileSync(out).toString('base64');
  }
}
await Promise.all(Array.from({ length: 6 }, worker));
rmSync(dir, { recursive: true, force: true });

const body = phrases.map(p => `  ${JSON.stringify(p)}: "${clips[p]}"`).join(',\n');
const block = `${BEGIN} – generated by tools/clips.mjs (${VOICE}, pitch ${PITCH}, rate ${RATE}), do not edit by hand */\nconst CLIPS = {\n${body}\n};\n`;
const a = html.indexOf(BEGIN), b = html.indexOf(END);
writeFileSync(FILE, html.slice(0, a) + block + html.slice(b));
const kb = Object.values(clips).reduce((s, c) => s + c.length, 0) / 1024;
console.log(`${phrases.length} clips, ${kb.toFixed(0)} KB of base64 written to index.html`);
